-- Buildings (from "Building charges details") and their flats and tenants (from "Tenants detailed report").
-- Only the flat, tenant name, security deposit and status are loaded: no Emirates IDs or email addresses.
CREATE TABLE "Building" (
    "id" TEXT NOT NULL, "code" TEXT, "name" TEXT NOT NULL, "billCycle" TEXT,
    "securityDeposit" DOUBLE PRECISION, "connectionCharge" DOUBLE PRECISION, "disconnectionCharge" DOUBLE PRECISION,
    "unitRate" DOUBLE PRECISION, "pressureFactor" DOUBLE PRECISION, "monthlyCharge" DOUBLE PRECISION, "firstBill" DOUBLE PRECISION,
    "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "Building_pkey" PRIMARY KEY ("id")
);
CREATE UNIQUE INDEX "Building_name_key" ON "Building"("name");

CREATE TABLE "Unit" (
    "id" TEXT NOT NULL, "buildingId" TEXT NOT NULL, "flat" TEXT NOT NULL, "tenantName" TEXT,
    "securityDeposit" DOUBLE PRECISION, "status" TEXT NOT NULL DEFAULT 'ACTIVE',
    "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "Unit_pkey" PRIMARY KEY ("id")
);
CREATE UNIQUE INDEX "Unit_buildingId_flat_key" ON "Unit"("buildingId", "flat");
ALTER TABLE "Unit" ADD CONSTRAINT "Unit_buildingId_fkey" FOREIGN KEY ("buildingId") REFERENCES "Building"("id") ON DELETE CASCADE ON UPDATE CASCADE;

-- Running numbers (service requests, SR-2026-NOV-0001).
CREATE TABLE "NumberCounter" ("key" TEXT NOT NULL, "last" INTEGER NOT NULL DEFAULT 0, CONSTRAINT "NumberCounter_pkey" PRIMARY KEY ("key"));

